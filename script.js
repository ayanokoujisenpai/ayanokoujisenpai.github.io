// <lookup-core>

// Turns "+63 994-731-4166", "63994...", "9947314166" and "0994 731 4166"
// into the local format "09947314166". Keep identical to build-data.js.
function toLocalNumber(input) {
  let digits = String(input).replace(/\D/g, "");
  if (digits.startsWith("63") && digits.length === 12)
    digits = "0" + digits.slice(2);
  else if (digits.startsWith("9") && digits.length === 10)
    digits = "0" + digits;
  return digits;
}

function isValidNumber(number) {
  return /^09\d{9}$/.test(number);
}

// Salted PBKDF2-SHA256, returned as hex. Must match build-data.js.
async function hashNumber(number, salt, iterations) {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    "raw",
    enc.encode(number),
    "PBKDF2",
    false,
    ["deriveBits"],
  );
  const bits = await crypto.subtle.deriveBits(
    {
      name: "PBKDF2",
      hash: "SHA-256",
      salt: enc.encode(salt),
      iterations: iterations,
    },
    key,
    256,
  );
  return Array.from(new Uint8Array(bits), (b) =>
    b.toString(16).padStart(2, "0"),
  ).join("");
}

async function findReport(number, reports, salt, iterations) {
  const hash = await hashNumber(number, salt, iterations);
  return reports.find((r) => r.hash === hash) || null;
}

// </lookup-core>

const form = document.getElementById("check-form");
const numberInput = document.getElementById("number");
const checkBtn = document.getElementById("check-btn");
const statusEl = document.getElementById("check-status");
const resultEl = document.getElementById("result");

let lastCheck = 0;

// Builds the result card. Only textContent is used, so data can never
// inject HTML into the page.
function showResult(paragraphs, { withContact = false } = {}) {
  resultEl.replaceChildren();
  paragraphs.forEach((text) => {
    const p = document.createElement("p");
    p.style = "text-align: center";
    p.textContent = text;
    resultEl.append(p);
  });
  if (withContact && CONTACT_URL) {
    const p = document.createElement("p");
    const a = document.createElement("a");
    a.href = CONTACT_URL;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    a.textContent = "Request a correction or removal";
    p.append(a);
    resultEl.append(p);
  }
  resultEl.hidden = false;
}

function setBusy(busy) {
  checkBtn.disabled = busy;
  checkBtn.textContent = busy ? "Checking…" : "Check number";
}

form.addEventListener("submit", async (e) => {
  e.preventDefault();
  resultEl.hidden = true;
  statusEl.textContent = "";

  if (typeof REPORTS === "undefined" || typeof SALT === "undefined") {
    statusEl.textContent =
      "The data file did not load. Refresh the page and try again.";
    return;
  }
  if (!window.crypto || !window.crypto.subtle) {
    statusEl.textContent =
      "This browser can't run the check. Open the site over https in an up-to-date browser.";
    return;
  }

  const number = toLocalNumber(numberInput.value);
  if (!isValidNumber(number)) {
    statusEl.textContent =
      "Enter the full 11-digit mobile number, like 0917 123 4567 or +63 917 123 4567.";
    numberInput.focus();
    return;
  }

  const wait = CHECK_COOLDOWN_MS - (Date.now() - lastCheck);
  if (wait > 0) {
    statusEl.textContent = `Please wait ${Math.ceil(wait / 1000)} seconds before checking again.`;
    return;
  }
  lastCheck = Date.now();

  setBusy(true);
  try {
    const hit = await findReport(number, REPORTS, SALT, ITERATIONS);
    if (hit) {
      showResult(
        [
          "✅✅ Record found! ✅✅",
          `I paid ${hit.amount} on ${hit.date} for ${hit.item} and had not received it as of ${hit.updated}.`,
          "This is one buyer's experience, feel free to message me if you need the proofs. If it is inaccurate, or the number has changed hands, please tell me and I will correct or remove it.",
        ],
        { withContact: true },
      );
    } else {
      showResult([
        "❌❌ No record found for this number. ❌❌",
        "Stay safe and good luck purchasing!",
      ]);
    }
  } catch (err) {
    statusEl.textContent = "Something went wrong while checking. Try again.";
  } finally {
    setBusy(false);
  }
});
