// Your contact link (Facebook profile, Messenger, Telegram, or an email as
// "mailto:you@example.com"). While this is empty, every "Contact me" link on
// the site stays hidden. Set this before launch: a working way to request a
// correction is part of running a list like this responsibly.
const CONTACT_URL = "";

// Minimum time between checks, in milliseconds. This only slows down casual
// clicking. It runs in the visitor's browser, so it is not real protection.
const CHECK_COOLDOWN_MS = 3000;

/* =========================================================
   Tabs
   ========================================================= */

const tabs = Array.from(document.querySelectorAll('[role="tab"]'));
const panels = Array.from(document.querySelectorAll('[role="tabpanel"]'));

function activateTab(tab, { focus = false, updateHash = true } = {}) {
  const panelId = tab.getAttribute("aria-controls");

  tabs.forEach((t) => {
    const selected = t === tab;
    t.setAttribute("aria-selected", String(selected));
    t.tabIndex = selected ? 0 : -1;
  });
  panels.forEach((p) => {
    p.hidden = p.id !== panelId;
  });

  if (focus) tab.focus();

  if (updateHash) {
    try {
      history.replaceState(null, "", "#" + panelId);
    } catch (err) {
      /* history can be blocked (e.g. file://). The tab still works. */
    }
  }
  window.scrollTo(0, 0);
}

function tabFromHash() {
  const id = location.hash.slice(1);
  return tabs.find((t) => t.getAttribute("aria-controls") === id);
}

function selectedIndex() {
  return tabs.findIndex((t) => t.getAttribute("aria-selected") === "true");
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => activateTab(tab));
});

// Arrow keys, Home and End move between tabs
document.querySelector('[role="tablist"]').addEventListener("keydown", (e) => {
  const last = tabs.length - 1;
  let next = null;
  if (e.key === "ArrowRight") next = (selectedIndex() + 1) % tabs.length;
  else if (e.key === "ArrowLeft")
    next = (selectedIndex() - 1 + tabs.length) % tabs.length;
  else if (e.key === "Home") next = 0;
  else if (e.key === "End") next = last;
  if (next === null) return;
  e.preventDefault();
  activateTab(tabs[next], { focus: true });
});

// Open the tab named in the URL (e.g. .../#check), and follow back/forward
const startTab = tabFromHash();
if (startTab) activateTab(startTab, { updateHash: false });

window.addEventListener("hashchange", () => {
  const tab = tabFromHash();
  if (tab) activateTab(tab, { updateHash: false });
});

/* =========================================================
   Swipe between tabs (touch screens)
   ========================================================= */

let touchStart = null;

document.addEventListener(
  "touchstart",
  (e) => {
    // Ignore multi-touch, and swipes that start in the input box
    if (e.touches.length !== 1 || e.target.closest("input")) {
      touchStart = null;
      return;
    }
    touchStart = { x: e.touches[0].clientX, y: e.touches[0].clientY };
  },
  { passive: true },
);

document.addEventListener(
  "touchend",
  (e) => {
    if (!touchStart) return;
    const touch = e.changedTouches[0];
    const dx = touch.clientX - touchStart.x;
    const dy = touch.clientY - touchStart.y;
    touchStart = null;

    const MIN_DISTANCE = 60;
    const isMostlyHorizontal = Math.abs(dx) >= Math.abs(dy) * 2;
    if (Math.abs(dx) < MIN_DISTANCE || !isMostlyHorizontal) return;
    if (String(window.getSelection())) return; // user is selecting text

    const next = tabs[selectedIndex() + (dx < 0 ? 1 : -1)];
    if (next) activateTab(next);
  },
  { passive: true },
);

